interface FixtureInput {
  id: string;
  tmdbId: number;
  title: string;
  synopsis: string;
  type: MediaType;
  runtime: number;
  year: number;
  genres: string[];
  moods: string[];
  companions: string[];
  rating: AgeRating;
  origin: string[];
  providers: OttProvider[];
  poster?: string;
  collection?: string;
  score: number;
  votes: number;
  color: string;
}

const providerUrl = (provider: OttProvider, title: string): string =>
  `https://www.google.com/search?q=${encodeURIComponent(`${provider} ${title}`)}`;

const makeContent = (input: FixtureInput): CatalogContent => ({
  id: input.id,
  tmdbId: input.tmdbId,
  title: input.title,
  synopsis: input.synopsis,
  mediaType: input.type,
  runtimeMinutes: input.runtime,
  releaseYear: input.year,
  genres: input.genres,
  moodTags: input.moods,
  companionTags: input.companions,
  ageRating: input.rating,
  originCountries: input.origin,
  productionCountries: input.origin,
  providers: input.providers.map((provider) => ({
    provider,
    watchUrl: providerUrl(provider, input.title),
    linkType: "SEARCH",
  })),
  collectionId: input.collection ?? null,
  voteAverage: input.score,
  voteCount: input.votes,
  posterUrl: input.poster
    ? `https://image.tmdb.org/t/p/w500${input.poster}`
    : null,
  backdropColor: input.color,
});

